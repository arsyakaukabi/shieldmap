    fig.suptitle(title, x=0.01, ha="left", fontsize=10.5, fontweight="bold")
    fig.text(0.01, 0.01, "Orange box: X is in the best (lowest-requirement) compound of the baseline set "
             "(scenarios: in \u2265 half of the primary sweep variants).\nKey-energy columns: single line; scenario "
             "columns: median over the primary sweep at the primary basis (DIAG areal, Cs-137/Co-60 thickness). "
             f"Rows: top {n_top} elements by max price over both panels; blank = 0.", fontsize=7, color=INK2)
    fig.savefig(path, dpi=300)
    plt.close(fig)


