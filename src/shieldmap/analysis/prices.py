def compute_shapley(df: pd.DataFrame, dm: pd.DataFrame) -> pd.DataFrame:
    names = [player_label(p) for p in PLAYERS]
    out = []
    for src, d, keys in (("profile", df, ["scenario", "variant_id"]), ("mono", dm, ["energy_keV"])):
        s = d[d.family == "subset"]
        for gk, g in s.groupby(keys + ["basis", "rule", "kind"], sort=False):
            vals = {frozenset(p for p in prm.split("+") if p): np.log(qc)
                    for prm, qc in zip(g["param"], g["q_constrained"])}
            v0 = vals[frozenset()]
            phi = core.shapley(names, lambda S: vals[frozenset(S)] - v0)
            total = vals[frozenset(names)] - v0
            base = dict(zip(keys + ["basis", "rule", "kind"], gk if isinstance(gk, tuple) else (gk,)))
            for n in names:
                out.append({**base, "source": src, "player": n, "phi": phi[n], "total": total,
                            "share": phi[n] / total if total != 0 else np.nan})
    return pd.DataFrame(out)


