def bundle_tables(rule: str = core.PRIMARY_RULE) -> tuple[pd.DataFrame, pd.DataFrame]:
    u = core.universe()
    v = core.variants()
    base = core.base_mask(rule)
    rows, stab = [], []
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        other = "thickness" if b == "areal" else "areal"
        q = np.asarray(core.profiles(b))
        qo = np.asarray(core.profiles(other))
        vid = DISPLAY_VARIANT[scen]
        sweep = core.scenario_variants(scen).variant_id.to_numpy()
        mu = mu_at(SCEN_KEY_E[scen]) if scen in SCEN_KEY_E else None
        for bn in core.BUNDLES:
            m = base & core.bundle_mask(bn)
            top = core.top_k(q[:, vid], m, 10)
            for rk, r in enumerate(top, 1):
                rows.append({
                    "scenario": scen, "rule": rule, "display_variant": vid,
                    "display_spectrum": v.spectrum[vid], "T_target": v.T_target[vid],
                    "bundle": bn, "rank": rk, "row": int(r), "material_id": u.material_id[r],
                    "formula": u.formula_pretty[r], "basis": b, "requirement": float(q[r, vid]),
                    "requirement_other_basis": float(qo[r, vid]), "other_basis": other,
                    "density": u.density[r],
                    "mu_key_cm-1": float(mu[r]) if mu is not None else np.nan,
                    "key_energy_keV": SCEN_KEY_E.get(scen, np.nan),
                    "e_hull": u.energy_above_hull[r], "theoretical": bool(u.theoretical[r]),
                    "band_gap": u.band_gap[r], "min_abundance_ppm": u.min_crustal_abundance_ppm[r],
                    "elements": "-".join(u.elements[r]),
                })
            tops = [set(core.top_k(q[:, j], m, 10)) for j in sweep]
            kept = set(top).intersection(*tops)
            union = set().union(*tops)
            stab.append({"scenario": scen, "rule": rule, "bundle": bn, "display_variant": vid,
                         "n_sweep_variants": len(sweep), "display_top10_in_all_top10": len(kept),
                         "distinct_compounds_in_any_top10": len(union)})
    return pd.DataFrame(rows), pd.DataFrame(stab)


