def load_bearing_matrix(df, dm, baseline="F0", mono_basis="thickness", rule="R2", kind="best"):
    """Element x column price matrix (%) and frontier-membership mask.

    Columns: the 14 key energies (single line, ``mono_basis``) + DIAG/CS137/CO60 at their primary
    basis (median across the primary sweep). Membership (always from the *best* frontier): X is in
    the best compound of the baseline set (for scenarios: in >= half of the sweep variants).
    """
    u = core.universe()
    els = core.element_list()
    cols = [f"{E:g}" for E in KEY_E] + list(SCENARIOS)
    P = pd.DataFrame(np.nan, index=els, columns=cols)
    M = pd.DataFrame(False, index=els, columns=cols)
    base_lab = "B0" if baseline == "F0" else "B4"
    m = dm[(dm.basis == mono_basis) & (dm.rule == rule)]
    ex = m[(m.family == "excl") & (m.baseline == baseline) & (m.kind == kind)]
    mb = m[(m.kind == "best") & (m.constraint == base_lab) & (m.family == "bundle")]
    for E in KEY_E:
        e = ex[ex.energy_keV == E].set_index("param").price
        P[f"{E:g}"] = e.reindex(els).to_numpy() * 100
        for x in u.elements[mb[mb.energy_keV == E].frontier_row.iloc[0]]:
            M.loc[x, f"{E:g}"] = True
    d = df[df.primary & (df.rule == rule)]
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        ds = d[(d.scenario == scen) & (d.basis == b)]
        e = ds[(ds.family == "excl") & (ds.baseline == baseline) & (ds.kind == kind)].groupby("param").price.median()
        P[scen] = e.reindex(els).to_numpy() * 100
        fr = ds[(ds.kind == "best") & (ds.constraint == base_lab) & (ds.family == "bundle")].frontier_row.to_numpy()
        cnt = pd.Series([x for r in fr for x in u.elements[r]]).value_counts()
        for x, c in cnt.items():
            if c >= len(fr) / 2:
                M.loc[x, scen] = True
    return P, M


