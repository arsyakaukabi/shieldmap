"""A2 — price of constraints.

Everything here goes through ``analysis.core``: the universe, the representative rules, the
constraint and bundle masks, the frontier q* and the Shapley values. This module only decides
*which* candidate sets to evaluate and writes the results.

Price of a constraint set K relative to a baseline set F (F = F0, or F0 ∩ B4 for the
"marginal on B4" element exclusions):   P = q*(F ∩ K) / q*(F) − 1   (core.price; see _evaluate).

Requirement sources
  profile   Table C requirement for the 264 profile variants (core.profiles), both bases.
  mono      single-line requirement at the key energies: thickness q = 1/μ (cm, μ = μ/ρ·ρ with the
            Table B density), areal q = 1/(μ/ρ) (g/cm²), μ/ρ from Table C (with coherent).
            For a single line the Table C requirement is ln(1/T)·q at any T, so prices are exact.

Outputs (all regenerated by run(); idempotent)
  data/phase2/A2/prices.parquet        long format, profile variants
  data/phase2/A2/prices_mono.parquet   long format, monoenergetic key energies
  data/phase2/A2/shapley.parquet       Shapley attribution of log q*(B4) − log q*(B0)
  data/phase2/A2/bundle_top10.parquet  (+ .csv) frontier compounds per bundle, display variants
  data/phase2/A2/bundle_top10_stability.csv
  data/phase2/A2/summary.json          headline numbers with ranges
  reports/phase2/A2_tables.md          every summary table (generated)
  reports/phase2/figures/A2_*.png
Run:  python -m shieldmap.analysis.prices
"""
