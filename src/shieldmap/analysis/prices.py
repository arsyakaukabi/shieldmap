def _evaluate(q: np.ndarray, sets, rules=core.RULES) -> list[dict]:
    """Frontier and price for every set × rule × kind, vectorised over the columns of q.

    Rows are restricted to F0(rule) first; core.frontier(q[F0], M[F0]) ≡ core.frontier(q, F0 ∧ M).
    The price equals core.price (checked in run()); the baseline frontier is cached per
    (rule, kind, baseline) instead of being recomputed for every constraint.
    """
    res = []
    for rule in rules:
        base = core.base_mask(rule)
        rows = np.flatnonzero(base)
        qb = np.ascontiguousarray(np.asarray(q)[base])
        cache: dict = {}
        for fam, lab, code, par, parv, bl, kmask, blmask in sets:
            km = (kmask & blmask)[base]
            bm = blmask[base]
            for kind in core.KINDS:
                key = (bl, kind)
                if key not in cache:
                    cache[key] = core.frontier(qb, bm, kind)
                qbase = cache[key]
                qk = core.frontier(qb, km, kind)
                rec = dict(family=fam, constraint=lab, code=code, param=par, param_value=parv,
                           baseline=bl, rule=rule, kind=kind, n_candidates=int(km.sum()),
                           q_base=qbase, q_constrained=qk, price=qk / qbase - 1.0)
                if kind == "best":
                    if km.any():
                        qm = np.where(km[:, None], qb, np.inf)
                        rec["frontier_row"] = rows[qm.argmin(axis=0)]   # ties → lowest row (= core.top_k)
                    else:
                        rec["frontier_row"] = np.full(q.shape[1], -1)
                else:
                    rec["frontier_row"] = np.full(q.shape[1], -1)
                res.append(rec)
    return res


def _to_frame(res: list[dict], colmeta: pd.DataFrame, basis: str) -> pd.DataFrame:
    """Expand per-set records (arrays over columns) into long format."""
    V = len(colmeta)
    frames = []
    for r in res:
        d = {k: np.repeat(r[k], V) for k in ("family", "constraint", "code", "param", "param_value",
                                              "baseline", "rule", "kind", "n_candidates")}
        d.update({k: np.asarray(r[k]) for k in ("q_base", "q_constrained", "price", "frontier_row")})
        f = pd.DataFrame(d)
        for c in colmeta.columns:
            f[c] = colmeta[c].to_numpy()
        f["basis"] = basis
        frames.append(f)
    return pd.concat(frames, ignore_index=True)


def _attach_ids(df: pd.DataFrame) -> pd.DataFrame:
    u = core.universe()
    r = df["frontier_row"].to_numpy()
    ok = r >= 0
    mid = np.full(len(df), None, dtype=object)
    frm = np.full(len(df), None, dtype=object)
    mid[ok] = u["material_id"].to_numpy()[r[ok]]
    frm[ok] = u["formula_pretty"].to_numpy()[r[ok]]
    df["frontier_material_id"] = mid
    df["frontier_formula"] = frm
    return df


def mono_requirements() -> dict[str, np.ndarray]:
    """(N × 14) single-line requirements: thickness 1/μ [cm], areal 1/(μ/ρ) [g/cm²]."""
    e = np.load(paths.PROCESSED / "energy_keV.npy")
    idx = [int(np.argmin(np.abs(e - E))) for E in KEY_E]
    assert np.allclose(e[idx], KEY_E), "key energy not on the grid"
    mr = np.asarray(np.load(paths.PROCESSED / "mu_rho_wcoh.npy", mmap_mode="r")[:, idx], dtype=np.float64)
    rho = core.universe()["density"].to_numpy(dtype=np.float64)
    with np.errstate(divide="ignore"):
        return {"areal": 1.0 / mr, "thickness": 1.0 / (mr * rho[:, None])}


def mu_at(E: float) -> np.ndarray:
    e = np.load(paths.PROCESSED / "energy_keV.npy")
    i = int(np.argmin(np.abs(e - E)))
    mr = np.asarray(np.load(paths.PROCESSED / "mu_rho_wcoh.npy", mmap_mode="r")[:, i], dtype=np.float64)
    return mr * core.universe()["density"].to_numpy(dtype=np.float64)


def compute_prices() -> tuple[pd.DataFrame, pd.DataFrame]:
    v = core.variants()
    meta_all = v[["scenario", "variant_id", "primary"]].reset_index(drop=True)
    assert (v.variant_id.to_numpy() == np.arange(len(v))).all()
    prim = v.index[v.primary].to_numpy()
    meta_prim = meta_all.iloc[prim].reset_index(drop=True)
    s_sb, s_ext = _sets_single_bundle(), _sets_extended()
    frames, mframes = [], []
    mono = mono_requirements()
    meta_mono = pd.DataFrame({"energy_keV": list(KEY_E)})
    for basis in core.BASES:
        q = np.asarray(core.profiles(basis))
        t = time.time()
        frames.append(_to_frame(_evaluate(q, s_sb), meta_all, basis))
        qp = np.ascontiguousarray(q[:, prim])
        frames.append(_to_frame(_evaluate(qp, s_ext), meta_prim, basis))
        mframes.append(_to_frame(_evaluate(mono[basis], s_sb + s_ext), meta_mono, basis))
        print(f"  [A2] {basis}: {time.time() - t:.0f} s", flush=True)
    df = _attach_ids(pd.concat(frames, ignore_index=True))
    dm = _attach_ids(pd.concat(mframes, ignore_index=True))
    first = ["scenario", "variant_id", "primary", "basis", "rule", "kind", "family", "constraint",
             "code", "param", "param_value", "baseline"]
    df = df[first + [c for c in df.columns if c not in first]]
    firstm = ["energy_keV", "basis", "rule", "kind", "family", "constraint", "code", "param",
              "param_value", "baseline"]
    dm = dm[firstm + [c for c in dm.columns if c not in firstm]]
    return df, dm


