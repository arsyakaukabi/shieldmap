def _rng(x) -> dict:
    return core.summarize_range(np.asarray(x, dtype=float) * 100.0)


def fmt_rng(r: dict, nd: int = 1) -> str:
    if r["n"] == 0:
        return "n/a"
    lo, hi = r["min"], r["max"]
    if abs(hi - lo) < 0.05 * 10 ** (1 - nd) or np.isclose(lo, hi, rtol=1e-6, atol=10 ** -(nd + 1)):
        return f"+{lo:.{nd}f}"
    return f"+{lo:.{nd}f} … +{hi:.{nd}f}"


def headline(df: pd.DataFrame, rule="R2", kind="best", basis=None, family=("single", "bundle"),
             constraints=None) -> pd.DataFrame:
    """Range across the primary sweep of each scenario, one row per (scenario, constraint)."""
    d = df[df.primary & (df.rule == rule) & (df.kind == kind) & df.family.isin(family)
           & (df.baseline == "F0")]
    rows = []
    for scen in SCENARIOS:
        b = basis or core.default_basis(scen)
        ds = d[(d.scenario == scen) & (d.basis == b)]
        for c, g in ds.groupby("constraint", sort=False):
            if constraints and c not in constraints:
                continue
            r = _rng(g.price)
            rows.append({"scenario": scen, "basis": b, "constraint": c, **r})
    return pd.DataFrame(rows)


def checks(df: pd.DataFrame, dm: pd.DataFrame) -> dict:
    """Consistency checks (asserted): equality with core.price, CS137 T-independence, mono = Table C."""
    res = {}
    # (a) our price == core.price for every single/bundle, R2, all kinds, thickness basis
    q = np.asarray(core.profiles("thickness"))
    base = core.base_mask("R2")
    worst = 0.0
    for s in _sets_single_bundle():
        for kind in core.KINDS:
            ref = core.price(q, base, s[6], kind)
            ours = df[(df.basis == "thickness") & (df.rule == "R2") & (df.kind == kind)
                      & (df.constraint == s[1]) & (df.baseline == "F0")
                      & df.family.isin(["single", "bundle"])].sort_values("variant_id").price.to_numpy()
            worst = max(worst, float(np.nanmax(np.abs(ours - ref))))
    res["max_abs_diff_vs_core_price"] = worst
    assert worst < 1e-12, worst
    # (b) CS137: identical prices for all 4 T (per basis/rule/kind/constraint)
    d = df[(df.scenario == "CS137") & df.primary]
    spread = d.groupby(["basis", "rule", "kind", "family", "constraint", "baseline"]).price.agg(
        lambda x: np.nanmax(x) - np.nanmin(x) if np.isfinite(x).any() else 0.0)
    res["cs137_max_price_spread_across_T"] = float(spread.max())
    assert spread.max() < 1e-5, spread.max()
    # (c) CS137 profile price == mono price at 661.657 keV (thickness and areal)
    ix = ["basis", "rule", "kind", "family", "constraint", "baseline"]
    a = d[d.variant_id == 38].set_index(ix).price
    m = dm[dm.energy_keV == 661.657].set_index(ix).price
    j = pd.concat([a, m], axis=1, join="inner").dropna()
    res["cs137_vs_mono661_max_abs_diff"] = float((j.iloc[:, 0] - j.iloc[:, 1]).abs().max())
    res["cs137_vs_mono661_n"] = int(len(j))
    assert res["cs137_vs_mono661_max_abs_diff"] < 1e-5, res["cs137_vs_mono661_max_abs_diff"]
    # (d) frontier row for kind=best reproduces q_constrained
    b = df[(df.kind == "best") & (df.frontier_row >= 0) & (df.basis == "thickness")].sample(
        2000, random_state=0)
    qq = q[b.frontier_row.to_numpy(), b.variant_id.to_numpy()]
    res["frontier_row_max_rel_err"] = float(np.max(np.abs(qq / b.q_constrained.to_numpy() - 1)))
    assert res["frontier_row_max_rel_err"] < 1e-6
    # (e) frontier row agrees with core.top_k (tie rule) on a sample
    for c in ("B4", "PB", "EXP"):
        r = df[(df.constraint == c) & (df.kind == "best") & (df.rule == "R2")
               & (df.basis == "thickness") & (df.variant_id == 13) & (df.baseline == "F0")]
        assert int(r.frontier_row.iloc[0]) == int(core.top_k(q[:, 13], base & (
            core.bundle_mask(c) if c.startswith("B") else core.constraint_mask(c)), 1)[0])
    return res


def _range_table(df, scen, basis, constraints, by=("rule", "kind")) -> pd.DataFrame:
    d = df[df.primary & (df.scenario == scen) & (df.basis == basis) & (df.baseline == "F0")
           & df.family.isin(["single", "bundle"]) & df.constraint.isin(constraints)]
    rows = []
    for c in constraints:
        g = d[d.constraint == c]
        row = {"constraint": c}
        for rule in core.RULES:
            for kind in core.KINDS:
                row[f"{rule}/{kind}"] = fmt_rng(_rng(g[(g.rule == rule) & (g.kind == kind)].price))
        row["all"] = fmt_rng(_rng(g.price))
        rows.append(row)
    return pd.DataFrame(rows)


def md_table(frame: pd.DataFrame, floatfmt: str = "{:.3g}") -> str:
    cols = list(frame.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in frame.iterrows():
        cells = []
        for c in cols:
            x = r[c]
            if isinstance(x, (float, np.floating)):
                cells.append("" if np.isnan(x) else floatfmt.format(x))
            else:
                cells.append(str(x))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


