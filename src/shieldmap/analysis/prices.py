def run(recompute: bool = True) -> dict:
    """Regenerate every A2 output. recompute=False reuses prices*.parquet (post-processing only)."""
    t0 = time.time()
    OUT.mkdir(parents=True, exist_ok=True)
    core.FIGURES.mkdir(parents=True, exist_ok=True)
    if recompute or not (OUT / "prices_mono.parquet").exists():
        df, dm = compute_prices()
        df.to_parquet(OUT / "prices.parquet", index=False)
        dm.to_parquet(OUT / "prices_mono.parquet", index=False)
    else:
        df = pd.read_parquet(OUT / "prices.parquet")
        dm = pd.read_parquet(OUT / "prices_mono.parquet")
    chk = checks(df, dm)
    print("  [A2] checks", chk, flush=True)
    sh = compute_shapley(df, dm)
    sh.to_parquet(OUT / "shapley.parquet", index=False)
    top, stab = bundle_tables()
    top.to_parquet(OUT / "bundle_top10.parquet", index=False)
    top.to_csv(OUT / "bundle_top10.csv", index=False)
    stab.to_csv(OUT / "bundle_top10_stability.csv", index=False)
    lb, lbm = {}, {}
    for bl in ("F0", "F0&B4"):
        for mb in ("thickness", "areal"):
            tag = f"{'F0' if bl == 'F0' else 'B4'}_{mb}"
            for kind in ("best", "median50"):
                P, M = load_bearing_matrix(df, dm, baseline=bl, mono_basis=mb, kind=kind)
                P.round(4).to_csv(OUT / f"load_bearing_{tag}_{kind}.csv")
                (lb if kind == "best" else lbm)[tag] = (P, M)
            M.to_csv(OUT / f"load_bearing_{tag}_frontier_member.csv")
    fig_price_bars(df, core.FIGURES / "A2_price_bars.png")
    fig_abund_curve(df, core.FIGURES / "A2_abund_curve.png")
    for tag, fn, ttl in (
            ("F0_thickness", "A2_load_bearing_heatmap.png",
             "Load-bearing elements: price of excluding element X from the map F0 (R2; key energies: thickness 1/\u03bc)"),
            ("F0_areal", "A2_load_bearing_heatmap_areal.png",
             "Load-bearing elements vs F0, areal basis at key energies (1/(\u03bc/\u03c1)); R2"),
            ("B4_thickness", "A2_load_bearing_heatmap_B4.png",
             "Load-bearing elements of the practical frontier: price of excluding X from F0 \u2229 B4 (R2; thickness)"),
            ("B4_areal", "A2_load_bearing_heatmap_B4_areal.png",
             "Load-bearing elements of F0 \u2229 B4, areal basis at key energies; R2")):
        fig_heatmap([("(a) best compound", *lb[tag]), ("(b) median of top-50", *lbm[tag])],
                    core.FIGURES / fn, ttl)
    fig_price_vs_energy(dm, core.FIGURES / "A2_price_vs_energy.png")
    summary = write_tables(df, dm, sh, top, stab, lb, lbm, chk)
    summary["runtime_s"] = round(time.time() - t0, 1)
    (OUT / "summary.json").write_text(json.dumps(summary, indent=1, default=float))
    print(f"  [A2] done in {time.time() - t0:.0f} s", flush=True)
    return summary


def write_tables(df, dm, sh, top, stab, lb, lbm, chk) -> dict:
    """Write reports/phase2/A2_tables.md (all generated tables) and return headline numbers."""
    L = ["# A2 generated tables", "",
         "Generated by `python -m shieldmap.analysis.prices`; do not edit by hand. Prices in %, "
         "as ranges (min … max) across the primary sweep unless stated. R2 = primary rule.", ""]
    summ: dict = {"checks": chk}
    names = BAR_SINGLES + ["STAB(0)", "STAB(0.025)", "STAB(0.1)", "GAP(2.5)", "GAP(3.5)",
                           "ABUND(0.01)", "ABUND(0.1)", "ABUND(10)"] + list(core.BUNDLES)
    # 1. headline table, both bases
    L += ["## 1. Single constraints and bundles (R2, best frontier, primary sweep)", ""]
    rows = []
    for c in names:
        row = {"constraint": c}
        for scen in SCENARIOS:
            for b in core.BASES:
                h = headline(df, basis=b, constraints=[c])
                h = h[h.scenario == scen]
                r = h.iloc[0][["n", "min", "median", "max"]].to_dict() if len(h) else {"n": 0}
                row[f"{scen} {b}{' *' if b == core.default_basis(scen) else ''}"] = fmt_rng(r)
                summ.setdefault("R2_best", {}).setdefault(scen, {}).setdefault(b, {})[c] = r
        rows.append(row)
    L += [md_table(pd.DataFrame(rows)), "", "\\* primary basis.", ""]
    # 2. robustness
    L += ["## 2. Robustness: price ranges by rule × frontier kind (primary basis, primary sweep)", ""]
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        L += [f"### {scen} ({b})", "", md_table(_range_table(df, scen, b, BAR_SINGLES + list(core.BUNDLES))), ""]
        full = {}
        for c in BAR_SINGLES + list(core.BUNDLES):
            g = df[df.primary & (df.scenario == scen) & (df.basis == b) & (df.baseline == "F0")
                   & df.family.isin(["single", "bundle"]) & (df.constraint == c)]
            full[c] = _rng(g.price)
        summ.setdefault("all_rules_kinds", {})[scen] = full
    # 3. Shapley
    L += ["## 3. Shapley attribution of log q*(B4) − log q*(B0)", "",
          "Share of the total log-price (φ_i / Σφ); range across the primary sweep. R2, best frontier.", ""]
    s = sh[(sh.source == "profile") & (sh.rule == "R2") & (sh.kind == "best")]
    rows = []
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        v = core.scenario_variants(scen).variant_id
        ss = s[(s.scenario == scen) & s.variant_id.isin(v) & (s.basis == b)]
        row = {"scenario": f"{scen} ({b})"}
        for p in [player_label(x) for x in PLAYERS]:
            g = ss[ss.player == p]
            r = core.summarize_range(g.share * 100)
            row[p] = f"{r['min']:.0f} … {r['max']:.0f} %" if r["max"] - r["min"] >= 0.5 else f"{r['median']:.0f} %"
            summ.setdefault("shapley_share_R2_best", {}).setdefault(scen, {})[p] = r
        tot = core.summarize_range(np.expm1(ss.groupby("variant_id").total.first()) * 100)
        row["total P(B4)"] = fmt_rng(tot)
        rows.append(row)
    L += [md_table(pd.DataFrame(rows)), ""]
    # robustness of Shapley
    rows = []
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        v = core.scenario_variants(scen).variant_id
        ss = sh[(sh.source == "profile") & (sh.scenario == scen) & sh.variant_id.isin(v) & (sh.basis == b)]
        for p in [player_label(x) for x in PLAYERS]:
            g = ss[ss.player == p]
            r = core.summarize_range(g.share * 100)
            rows.append({"scenario": scen, "player": p, "min share %": r["min"], "median %": r["median"],
                         "max share %": r["max"]})
    L += ["Shares across sweep × rules × kinds:", "", md_table(pd.DataFrame(rows), "{:.1f}"), ""]
    # mono Shapley
    sm = sh[(sh.source == "mono") & (sh.rule == "R2") & (sh.kind == "best") & (sh.basis == "thickness")]
    piv = sm.pivot_table(index="energy_keV", columns="player", values="share", dropna=False) * 100
    piv = piv.reindex(list(KEY_E))
    piv["total P(B4) %"] = np.expm1(sm.groupby("energy_keV").total.first()).reindex(list(KEY_E)) * 100
    L += ["Single line, thickness basis (R2, best): Shapley shares (%) by energy", "",
          md_table(piv.reset_index(), "{:.1f}"), ""]
    # 4. interactions
    L += ["## 4. Subset prices and pairwise interactions (R2, best, primary basis)", "",
          "Interaction I(A,B) = log(1+P_AB) − log(1+P_A) − log(1+P_B) (0 = additive in log q*); "
          "reported as median over the sweep, in % of log-units ×100.", ""]
    rows = []
    sub = df[(df.family == "subset") & (df.rule == "R2") & (df.kind == "best") & df.primary]
    pl = [player_label(x) for x in PLAYERS]
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        g = sub[(sub.scenario == scen) & (sub.basis == b)]
        lp = g.pivot_table(index="variant_id", columns="param", values="q_constrained")
        lp = np.log(lp.div(lp[""], axis=0))
        for r in range(1, 5):
            for s_ in itertools.combinations(pl, r):
                key = "+".join(s_)
                pr = np.expm1(lp[key]) * 100
                row = {"scenario": scen, "subset": "{" + ",".join(s_) + "}",
                       "P range": fmt_rng(core.summarize_range(pr))}
                if r == 2:
                    inter = (lp[key] - lp[s_[0]] - lp[s_[1]]) * 100
                    row["I(A,B)×100 median"] = f"{inter.median():+.2f}"
                    row["sum of singles P"] = fmt_rng(core.summarize_range(
                        (np.expm1(lp[s_[0]]) + np.expm1(lp[s_[1]])) * 100))
                rows.append(row)
    L += [md_table(pd.DataFrame(rows).fillna("")), ""]
    # 5. load-bearing
    for kind, dct in (("best", lb), ("median50", lbm)):
        for tag, (P, M) in dct.items():
            mx = P.max(axis=1)
            topn = mx[mx >= 0.05].sort_values(ascending=False).head(25).index
            L += [f"## 5. Load-bearing elements: {tag}, kind {kind} (price %, R2)", "",
                  f"Elements with any price >= 0.05 %: {int((mx >= 0.05).sum())} of {len(mx)} (top 25 shown). "
                  "Key-energy columns: single line; scenario columns: median across the primary sweep, "
                  "primary basis. `*` = element in the best compound of the baseline set.", ""]
            T = P.loc[topn].round(1).astype(str) + np.where(M.loc[topn], "*", "")
            L += [md_table(T.reset_index().rename(columns={"index": "element"})), ""]
    # load-bearing with ranges for scenarios (F0)
    L += ["### Scenario P(EXCL-X) ranges (F0, R2, best, primary basis, primary sweep), elements with max > 0.5 %", ""]
    rows = []
    ex = df[(df.family == "excl") & (df.baseline == "F0") & (df.rule == "R2") & (df.kind == "best") & df.primary]
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        g = ex[(ex.scenario == scen) & (ex.basis == b)].groupby("param").price
        mx = g.max().sort_values(ascending=False)
        for x in mx[mx > 0.005].index:
            rows.append({"scenario": scen, "element": x, "P range": fmt_rng(_rng(g.get_group(x)))})
    L += [md_table(pd.DataFrame(rows)), ""]
    # robust load-bearing (kinds/rules)
    L += ["### P(EXCL-X) across rules × kinds (F0, primary basis, primary sweep), top 10 per scenario by R2/best max", ""]
    rows = []
    exa = df[(df.family == "excl") & (df.baseline == "F0") & df.primary]
    for scen in SCENARIOS:
        b = core.default_basis(scen)
        g0 = ex[(ex.scenario == scen) & (ex.basis == b)].groupby("param").price.max().sort_values(ascending=False)
        for x in g0.head(10).index:
            g = exa[(exa.scenario == scen) & (exa.basis == b) & (exa.param == x)]
            row = {"scenario": scen, "element": x}
            for kind in core.KINDS:
                row[kind] = fmt_rng(_rng(g[g.kind == kind].price))
            row["R1..R3 × kinds"] = fmt_rng(_rng(g.price))
            rows.append(row)
    L += [md_table(pd.DataFrame(rows)), ""]
    # 6. bundle frontier compounds
    L += ["## 6. Frontier compounds per bundle (R2, top 10, display variant)", ""]
    for scen in SCENARIOS:
        t = top[top.scenario == scen]
        L += [f"### {scen}: display variant {t.display_variant.iloc[0]} ({t.display_spectrum.iloc[0]}, "
              f"T = {t.T_target.iloc[0]:.4g}); requirement basis {t.basis.iloc[0]}", ""]
        cols = ["bundle", "rank", "material_id", "formula", "requirement", "requirement_other_basis",
                "density", "e_hull", "theoretical", "band_gap", "min_abundance_ppm"]
        if scen in SCEN_KEY_E:
            cols.insert(6, "mu_key_cm-1")
        L += [md_table(t[cols], "{:.4g}"), ""]
    L += ["### Top-10 stability across the primary sweep", "", md_table(stab), ""]
    # 7. mono prices table
    L += ["## 7. Single-line prices vs energy (R2, best, thickness basis 1/μ; areal in parentheses)", ""]
    cs = ["PB", "RAD", "STAB(0.05)", "EXP", "GAP(3.1)", "ABUND(1)", "B1", "B2", "B3", "B4", "B5", "B6"]
    d = dm[(dm.rule == "R2") & (dm.kind == "best") & (dm.baseline == "F0") & dm.family.isin(["single", "bundle"])]
    pt = d[d.basis == "thickness"].pivot_table(index="energy_keV", columns="constraint", values="price")[cs] * 100
    pa = d[d.basis == "areal"].pivot_table(index="energy_keV", columns="constraint", values="price")[cs] * 100
    T = pt.round(1).astype(str) + " (" + pa.round(1).astype(str) + ")"
