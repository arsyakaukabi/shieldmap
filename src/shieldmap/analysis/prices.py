def _sets_single_bundle():
    """(family, constraint label, code, param, param_value, baseline, K-mask, baseline-mask)."""
    u = core.universe()
    ones = np.ones(len(u), bool)
    out = []
    for code, p in SINGLES:
        out.append(("single", label(code, p), code, "" if p is None else f"{p:g}",
                    np.nan if p is None else float(p), "F0", core.constraint_mask(code, p), ones))
    for b in core.BUNDLES:
        out.append(("bundle", b, b, "", np.nan, "F0", core.bundle_mask(b), ones))
    return out


def _sets_extended():
    """Element exclusions (vs F0 and vs F0∩B4), the fine ABUND curve (alone and on B4), 16 subsets."""
    u = core.universe()
    ones = np.ones(len(u), bool)
    b4 = core.bundle_mask("B4")
    out = []
    for x in core.element_list():
        m = core.constraint_mask("EXCL", x)
        out.append(("excl", f"EXCL-{x}", "EXCL", x, np.nan, "F0", m, ones))
        out.append(("excl", f"EXCL-{x}", "EXCL", x, np.nan, "F0&B4", b4 & m, b4))
    for a in ABUND_FINE:
        m = core.constraint_mask("ABUND", a)
        out.append(("abund_fine", f"ABUND({a:g})", "ABUND", f"{a:g}", float(a), "F0", m, ones))
        out.append(("abund_fine_B4", f"B4+ABUND({a:g})", "B4+ABUND", f"{a:g}", float(a), "F0",
                    b4 & m, ones))
    pm = {player_label(p): core.constraint_mask(*p) for p in PLAYERS}
    for r in range(len(PLAYERS) + 1):
        for s in itertools.combinations(pm, r):
            m = ones.copy()
            for k in s:
                m &= pm[k]
            out.append(("subset", "{" + ",".join(s) + "}", "SUBSET", "+".join(s), np.nan, "F0", m, ones))
    return out


